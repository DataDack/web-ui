// ── Palette (grouped by category) ────────────────────────────────────────────

export function getNodePalette() {
  const grouped = {};
  // Collect subcategory groups per category: { 'Triggers': { 'App Trigger': [...items] } }
  const subgroups = {};

  for (const [key, def] of Object.entries(N8N_NODE_REGISTRY)) {
    const cat = def.category;
    if (!grouped[cat]) grouped[cat] = [];

    if (def.subcategory) {
      // Collect into subcategory group
      if (!subgroups[cat]) subgroups[cat] = {};
      if (!subgroups[cat][def.subcategory]) subgroups[cat][def.subcategory] = [];
      subgroups[cat][def.subcategory].push({ ...def, registryKey: key });
    } else {
      grouped[cat].push({ ...def, registryKey: key });
    }
  }

  // Inject subcategory parent items into their category
  for (const [cat, subs] of Object.entries(subgroups)) {
    if (!grouped[cat]) grouped[cat] = [];
    for (const [subName, children] of Object.entries(subs)) {
      grouped[cat].push({
        label: subName,
        description: `${children.length} app triggers`,
        icon: 'Bell',
        color: '#E5534B',
        registryKey: `__sub__${subName}`,
        isSubcategoryParent: true,
        children,
      });
    }
  }

  const order = [
    NODE_CATEGORIES.TRIGGERS,
    NODE_CATEGORIES.ACTIONS,
    NODE_CATEGORIES.LOGIC,
    NODE_CATEGORIES.DATA,
    NODE_CATEGORIES.AI,
    NODE_CATEGORIES.INTEGRATIONS,
    NODE_CATEGORIES.CRM,
    NODE_CATEGORIES.COMMUNICATION,
    NODE_CATEGORIES.MARKETING,
    NODE_CATEGORIES.DEVELOPER_TOOLS,
    NODE_CATEGORIES.PRODUCTIVITY,
    NODE_CATEGORIES.FINANCE,
    NODE_CATEGORIES.ECOMMERCE,
    NODE_CATEGORIES.CLOUD,
    NODE_CATEGORIES.DATABASES,
    NODE_CATEGORIES.UTILITY,
  ];
  return order
    .filter((cat) => grouped[cat])
    .map((cat) => ({ category: cat, items: grouped[cat] }));
}

// ── Helpers ──────────────────────────────────────────────────────────────────

export function getNodeDefaults(registryKey) {
  const def = N8N_NODE_REGISTRY[registryKey];
  return def ? JSON.parse(JSON.stringify(def.defaults)) : {};
}

export function getNodeDefinition(registryKey) {
  return N8N_NODE_REGISTRY[registryKey] || null;
}

export function findRegistryKeyByN8nType(n8nType) {
  for (const [key, def] of Object.entries(N8N_NODE_REGISTRY)) {
    if (def.n8nType === n8nType) return key;
  }
  return null;
}
